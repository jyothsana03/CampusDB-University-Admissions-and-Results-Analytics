md("### Chart 1: admissions trend per programme")
code('''
adm = query("""SELECT p.programme_code, s.admission_year AS year, COUNT(*) AS admitted
               FROM student s JOIN programme p ON p.programme_id = s.programme_id
               GROUP BY 1, 2 ORDER BY 1, 2""")
piv = adm.pivot(index="year", columns="programme_code", values="admitted")
order = piv.iloc[-1].sort_values(ascending=False).index          # legend order = latest value, high to low
fig, ax = plt.subplots(figsize=(3.6, 2.6))
for code_ in order:
    ax.plot(piv.index, piv[code_], color=SERIES[code_], lw=2, marker="o", ms=4, mec="white", mew=1.2, label=code_)
ax.set_xticks(piv.index); ax.set_ylim(0, 30)
ax.grid(axis="y", color=GRID, lw=0.8); ax.set_axisbelow(True)
ax.set_title("New students per year, by programme", loc="left", fontsize=9, fontweight="bold", color=INK)
ax.legend(ncol=3, frameon=False, fontsize=7.5, loc="upper center", bbox_to_anchor=(0.5, -0.12), handlelength=1.4, columnspacing=1.2)
fig.tight_layout()
finish(fig, "chart1_admissions_trend")
tot = piv.sum(axis=1)
print("total admitted per year:", tot.to_dict())
print(f"2021 -> 2025 growth: {tot[2025] / tot[2021] - 1:.0%}; MDS {piv.MDS[2021]} -> {piv.MDS[2025]}; BMA {piv.BMA[2021]} -> {piv.BMA[2025]}")
''')

