toppers = query("""
    WITH ranked AS (SELECT p.programme_code, s.reg_no, s.full_name, s.cgpa,
                           RANK() OVER (PARTITION BY s.programme_id ORDER BY s.cgpa DESC) AS rnk
                    FROM student s JOIN programme p USING (programme_id))
    SELECT programme_code, reg_no, full_name, cgpa FROM ranked WHERE rnk = 1 ORDER BY programme_code""")
print("Topper per programme"); print(toppers.to_string(index=False))
risk = query("SELECT COUNT(*) AS below_5 FROM student WHERE cgpa < 5.0").below_5[0]
n_students = query("SELECT COUNT(*) AS n FROM student").n[0]
