def b64png(fig):
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=110, facecolor="white")
    return base64.b64encode(buf.getvalue()).decode()

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ns = {"__name__": "__main__", "sys": sys}
nb_cells, exec_no, failed = [], 0, False
for ctype, src in cells:
    lines = src.split("\n")
    source = [l + "\n" for l in lines[:-1]] + [lines[-1]]
    if ctype == "markdown":
        nb_cells.append({"cell_type": "markdown", "metadata": {}, "source": source})
        continue
    exec_no += 1
    out_stream, figs = io.StringIO(), []
    plt.show = lambda *a, **k: (figs.append(b64png(plt.gcf())), plt.close("all"))
    outputs = []
    try:
        with contextlib.redirect_stdout(out_stream):
            exec(compile(src, f"cell{exec_no}", "exec"), ns)
    except Exception:
        failed = True
        outputs.append({"output_type": "error", "ename": "Error", "evalue": "see traceback", "traceback": traceback.format_exc().splitlines()})
        print(traceback.format_exc(), file=sys.stderr)
    text = out_stream.getvalue()
    if text:
        outputs.insert(0, {"output_type": "stream", "name": "stdout", "text": [l + "\n" for l in text.rstrip("\n").split("\n")]})
    for png in figs:
        outputs.append({"output_type": "display_data", "metadata": {}, "data": {"image/png": png, "text/plain": ["<Figure>"]}})
    nb_cells.append({"cell_type": "code", "execution_count": exec_no, "metadata": {}, "outputs": outputs, "source": source})

nb = {"cells": nb_cells, "nbformat": 4, "nbformat_minor": 5,
      "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                   "language_info": {"name": "python"}}}
(ROOT / "campusdb_analysis.ipynb").write_text(json.dumps(nb, indent=1))
print("notebook written; code cells:", exec_no, "| failed:", failed)
sys.exit(1 if failed else 0)
