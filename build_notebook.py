bars = ax.bar(band.entrance_band, band.avg_cgpa, color=SERIES["BCS"], width=0.55)
for b, v, n in zip(bars, band.avg_cgpa, band.students):
    ax.text(b.get_x() + b.get_width() / 2, v + 0.15, f"{v:.2f}", ha="center", fontsize=8, color=INK)
    ax.text(b.get_x() + b.get_width() / 2, 0.25, f"n={n}", ha="center", fontsize=7, color="white")
ax.set_ylim(0, 10); ax.grid(axis="y", color=GRID, lw=0.8); ax.set_axisbelow(True)
ax.set_xlabel("entrance score band", fontsize=7.5); ax.set_ylabel("average CGPA", fontsize=7.5)
ax.set_title("Entrance score vs CGPA", loc="left", fontsize=9, fontweight="bold", color=INK)
