md("## 2. Load the CSV files with `executemany` (parent tables first)")
code('''
LOAD_ORDER = ["department", "programme", "course", "student", "enrolment", "exam", "result"]
loaded = {}
for table in LOAD_ORDER:
    with open(f"data/{table}.csv", newline="") as f:
        rows = list(csv.reader(f))
    header, body = rows[0], rows[1:]
    sql = f"INSERT INTO {table} ({', '.join(header)}) VALUES ({', '.join(['%s'] * len(header))})"
    cur.executemany(sql, body)                         # result rows fire the CGPA trigger
    loaded[table] = len(body)
conn.commit()
for t in LOAD_ORDER:                                   # keep SERIAL sequences in step with the loaded ids
    pk = {"department": "dept_id", "programme": "programme_id"}.get(t, t + "_id")
    cur.execute(f"SELECT setval(pg_get_serial_sequence('{t}', '{pk}'), (SELECT MAX({pk}) FROM {t}))")
conn.commit()
print(loaded)
print("total rows loaded:", sum(loaded.values()))
''')

md("## 3. Helper: run SQL, get a pandas DataFrame")
code('''
def query(sql, params=None):
    cur.execute(sql, params)
    cols = [d[0] for d in cur.description]
    df = pd.DataFrame(cur.fetchall(), columns=cols)
    for c in df.columns:                               # psycopg2 returns Decimal/str, the shim returns str
        try:
            df[c] = pd.to_numeric(df[c])
        except (ValueError, TypeError):
            pass
    return df

counts = query("""
    SELECT 'department' AS tbl, COUNT(*) AS n FROM department UNION ALL
    SELECT 'programme', COUNT(*) FROM programme UNION ALL SELECT 'course', COUNT(*) FROM course UNION ALL
    SELECT 'student', COUNT(*) FROM student UNION ALL SELECT 'enrolment', COUNT(*) FROM enrolment UNION ALL
    SELECT 'exam', COUNT(*) FROM exam UNION ALL SELECT 'result', COUNT(*) FROM result""")
print(counts.to_string(index=False))
print("TOTAL ROWS:", int(counts.n.sum()))
''')

md("## 4. Trigger from Python: CGPA recomputes when a mark changes")
code('''
sid = 1
before = query("SELECT reg_no, cgpa FROM student WHERE student_id = %s", (sid,))
rid, old_marks = query("""SELECT r.result_id, r.marks_obtained FROM result r
                          JOIN enrolment e USING (enrolment_id)
                          WHERE e.student_id = %s ORDER BY r.result_id LIMIT 1""", (sid,)).iloc[0]
cur.execute("UPDATE result SET marks_obtained = %s WHERE result_id = %s", (99, int(rid)))
after = query("SELECT cgpa FROM student WHERE student_id = %s", (sid,))
cur.execute("UPDATE result SET marks_obtained = %s WHERE result_id = %s", (float(old_marks), int(rid)))   # restore
restored = query("SELECT cgpa FROM student WHERE student_id = %s", (sid,))
print(f"{before.reg_no[0]}: CGPA {before.cgpa[0]}  ->  {after.cgpa[0]} (one mark {old_marks} -> 99)  ->  {restored.cgpa[0]} (restored)")
try:
    cur.execute("UPDATE result SET marks_obtained = 120 WHERE result_id = %s", (int(rid),))
except Exception as e:
    print("validation trigger rejected marks 120:", str(e).splitlines()[0])
''')

